export function getRelatedPhones(phone: IPhone, count = 4): IPhone[] {
  return MOCK_IPHONES.filter((candidate) => candidate.slug !== phone.slug)
    .sort((a, b) => {
      const score = (item: IPhone) =>
        (item.releaseYear === phone.releaseYear ? 4 : 0) +
        (item.series === phone.series ? 3 : 0) +
        (Math.abs(item.releaseYear - phone.releaseYear) === 1 ? 2 : 0) -
        Math.abs(item.launchMsrpUsd - phone.launchMsrpUsd) / 1000;
      return score(b) - score(a);
    })
    .slice(0, count);
}
